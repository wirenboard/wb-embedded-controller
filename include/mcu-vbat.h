#pragma once

void mcu_vbat_init(void);
void mcu_vbat_check_do_periodic_work(void);

// Триггерит внеочередной тест тока принятия заряда батарейки.
// Прерывает текущее состояние (в т.ч. зарядку); если тест покажет
// разряженную батарейку, зарядка перезапустится сама.
void mcu_vbat_trigger_measurement(void);

// Принудительно запускает полный цикл зарядки без теста:
// включает PWR_CR4_VBE и сбрасывает счётчик времени зарядки.
void mcu_vbat_restart_charging(void);

// Останавливает зарядку и возвращает алгоритм в IDLE.
// Обязательно вызывать перед уходом в standby: бит VBE сохраняется
// в standby, и без этого заряд продолжался бы без контроля всё время сна.
void mcu_vbat_stop_charging(void);
